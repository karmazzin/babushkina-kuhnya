import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../dist/',import.meta.url),sw=new URL('sw.js',root);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
async function files(dir,prefix=''){
 const out=[];for(const entry of await readdir(dir,{withFileTypes:true})){
  if(entry.isDirectory())out.push(...await files(new URL(entry.name+'/',dir),prefix+entry.name+'/'));
  else if(prefix+entry.name!=='sw.js')out.push(prefix+entry.name);
 }return out.sort();
}
const index=new URL('index.html',root),html=await readFile(index,'utf8');
const stamp=/name="kitchen-version" content="[^"]*"/;
if(!stamp.test(html))throw Error('Missing page version marker');
// Normalize the stamp for release identity, then hash the actual stamped HTML for integrity.
const neutral=html.replace(stamp,'name="kitchen-version" content="BUILD"');
const hashes={};for(const path of await files(root))hashes[path]=sha(path==='index.html'?neutral:await readFile(new URL(path,root)));
const source=await readFile(sw,'utf8'),pattern=/\/\/ BEGIN RELEASE[\s\S]*?\/\/ END RELEASE/;
if(!pattern.test(source))throw Error('Missing release marker');
const id=sha(JSON.stringify(hashes)+source.replace(pattern,'// RELEASE')).slice(0,16);
const stamped=html.replace(stamp,`name="kitchen-version" content="1.0.0 · ${id.slice(0,8)}"`);
hashes['index.html']=sha(stamped);
const generated=`// BEGIN RELEASE (generated by npm run build)\nconst CACHE='babushkina-kuhnya-${id}';\nconst HASHES=${JSON.stringify(hashes,null,1)};\n// END RELEASE`;
const output=source.replace(pattern,generated);
if(process.argv.includes('--check')){if(output!==source||stamped!==html)throw Error('Release hashes are stale: run npm run build');}
else{if(stamped!==html)await writeFile(index,stamped);if(output!==source)await writeFile(sw,output);}
console.log(`Release ${id}: ${Object.keys(hashes).length} verified files`);
